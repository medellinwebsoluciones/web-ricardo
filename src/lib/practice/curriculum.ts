export function interviewPanels() {
  return AUDITOR_PANELS.map((p) => ({
    id: p.id,
    name: p.name,
    audience: p.audience,
    description: p.description,
  }));
}

export function questionsForPanel(
  panelId: string,
  locale: "en" | "es",
  difficulty?: PracticeDifficulty,
  limit = 8,
) {
  let qs = INTERVIEW_QUESTIONS.filter((q) => q.panel === panelId);
  if (difficulty) qs = qs.filter((q) => q.difficulty === difficulty);
  return qs.slice(0, limit).map((q) => ({
    id: q.id,
    text: locale === "en" ? q.en : q.es,
    mustCover: q.mustCover,
    redFlags: q.redFlags,
    difficulty: q.difficulty,
    audience: q.audience,
  }));
}


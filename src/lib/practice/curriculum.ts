export function getDrill(id: string): DrillItem | undefined {
  return DRILL_BANK.find((d) => d.id === id);
}

export function nextDrill(excludeIds: string[] = []): DrillItem {
  const pool = DRILL_BANK.filter((d) => !excludeIds.includes(d.id));
  const list = pool.length ? pool : DRILL_BANK;
  return list[Math.floor(Math.random() * list.length)]!;
}
